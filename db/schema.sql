-- aura database schema (PostgreSQL 15+, hosted on Supabase)
-- Safe to re-run: drops every aura object first, then recreates it.
-- WARNING: re-running wipes all aura data. Run db/seed.sql afterwards.

BEGIN;

-- ---------------------------------------------------------------------------
-- Clean slate
-- ---------------------------------------------------------------------------
DROP VIEW  IF EXISTS okr_metrics;
DROP VIEW  IF EXISTS group_shared_interests;
-- events and group_event_attendance were removed (migration 002); still dropped here so a reset cleans old databases.
DROP TABLE IF EXISTS
  meetups, group_event_attendance, events, chat_suggestions, messages, chat_participants, chats,
  group_matches, group_likes, friendships, user_interests, interests,
  user_photos, group_memberships, friend_groups, users
  CASCADE;
DROP FUNCTION IF EXISTS enforce_group_member_cap() CASCADE;
DROP FUNCTION IF EXISTS enforce_chat_participant_cap() CASCADE;
DROP TYPE IF EXISTS like_decision;
DROP TYPE IF EXISTS group_role;

CREATE TYPE like_decision AS ENUM ('connect', 'pass');
CREATE TYPE group_role    AS ENUM ('owner', 'member');

-- ---------------------------------------------------------------------------
-- People
-- ---------------------------------------------------------------------------
CREATE TABLE users (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name          varchar(50)  NOT NULL CHECK (btrim(first_name) <> ''),
  last_name           varchar(50)  NOT NULL CHECK (btrim(last_name) <> ''),
  city                varchar(80)  NOT NULL CHECK (btrim(city) <> ''),
  bio                 text         CHECK (char_length(bio) <= 500),
  age                 smallint     CHECK (age BETWEEN 18 AND 120),
  gender              varchar(30),
  relationship_status varchar(30)  CHECK (relationship_status IN
                        ('single', 'in_a_relationship', 'married', 'its_complicated', 'prefer_not_to_say')),
  personality_traits  text[]       NOT NULL DEFAULT '{}' CHECK (cardinality(personality_traits) <= 5),
  avatar_color        char(7)      NOT NULL DEFAULT '#FDDCCB' CHECK (avatar_color ~ '^#[0-9A-Fa-f]{6}$'),
  active_group_id     bigint,      -- FK added below, once group_memberships exists
  -- The Supabase Auth account that signs in as this user (NULL for seeded users without a demo login).
  -- FK to auth.users added below when this login is allowed to reference it.
  auth_user_id        uuid         UNIQUE,
  created_at          timestamptz  NOT NULL DEFAULT now()
);

-- Supabase only lets the `postgres` login reference auth.users. Run as aura_app, the reset
-- skips the FK with a warning (rerun db/migrations/003_auth_users.sql in the SQL Editor to add it).
DO $$
BEGIN
  -- NULL (no access to the auth schema at all) counts as false.
  IF (SELECT has_table_privilege('auth.users', 'REFERENCES') WHERE has_schema_privilege('auth', 'USAGE')) THEN
    ALTER TABLE users ADD CONSTRAINT users_auth_user_id_fkey
      FOREIGN KEY (auth_user_id) REFERENCES auth.users(id) ON DELETE SET NULL;
  ELSE
    RAISE WARNING 'users.auth_user_id has no foreign key to auth.users: run db/migrations/003_auth_users.sql in the Supabase SQL Editor.';
  END IF;
END $$;

CREATE TABLE user_photos (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     bigint      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  -- Position 1 is the main photo; 2-4 are the 3 more shown under it. With the UNIQUE below: max 4.
  position    smallint    NOT NULL CONSTRAINT user_photos_position_check CHECK (position BETWEEN 1 AND 4),
  label       varchar(60) NOT NULL,
  image_url   text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  -- DEFERRABLE so "Make main" can swap two positions in one UPDATE.
  CONSTRAINT user_photos_user_id_position_key UNIQUE (user_id, position) DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE interests (
  id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name  varchar(40) NOT NULL UNIQUE CHECK (btrim(name) <> '')
);
-- "hiking" and "Hiking" are the same interest.
CREATE UNIQUE INDEX interests_name_lower_idx ON interests (lower(name));

CREATE TABLE user_interests (
  user_id     bigint      NOT NULL REFERENCES users(id)     ON DELETE CASCADE,
  interest_id bigint      NOT NULL REFERENCES interests(id) ON DELETE CASCADE,
  added_at    timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, interest_id)
);

CREATE TABLE friendships (
  user_low_id   bigint      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  user_high_id  bigint      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at    timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_low_id, user_high_id),
  CHECK (user_low_id < user_high_id)   -- one row per pair, no self-friendship
);
CREATE INDEX friendships_high_idx ON friendships (user_high_id);

-- ---------------------------------------------------------------------------
-- Groups
-- ---------------------------------------------------------------------------
CREATE TABLE friend_groups (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          varchar(60)  NOT NULL CHECK (btrim(name) <> ''),
  city          varchar(80)  NOT NULL,
  latitude      numeric(9,6) CHECK (latitude  BETWEEN -90  AND 90),
  longitude     numeric(9,6) CHECK (longitude BETWEEN -180 AND 180),
  photo_label   varchar(60)  NOT NULL DEFAULT 'Group photo',
  photo_url     text,         -- the group photo in Supabase Storage (owner uploads), or null
  avatar_color  char(7)      NOT NULL DEFAULT '#ECE8FF' CHECK (avatar_color ~ '^#[0-9A-Fa-f]{6}$'),
  invite_code   varchar(12)  NOT NULL UNIQUE DEFAULT upper(substr(md5(random()::text), 1, 8)),
  created_by    bigint       REFERENCES users(id) ON DELETE SET NULL,
  created_at    timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE group_memberships (
  group_id   bigint      NOT NULL REFERENCES friend_groups(id) ON DELETE CASCADE,
  user_id    bigint      NOT NULL REFERENCES users(id)         ON DELETE CASCADE,
  role       group_role  NOT NULL DEFAULT 'member',
  joined_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (group_id, user_id),
  UNIQUE (user_id, group_id)   -- target for users' active-group FK; also indexes "my groups"
);

-- A user's active group must be one of their own groups. If they leave it
-- (membership row deleted), only active_group_id is cleared.
ALTER TABLE users
  ADD CONSTRAINT users_active_group_is_membership
  FOREIGN KEY (id, active_group_id)
  REFERENCES group_memberships (user_id, group_id)
  ON DELETE SET NULL (active_group_id);

-- Business rule: a Friend Group has at most 10 members.
CREATE FUNCTION enforce_group_member_cap() RETURNS trigger
LANGUAGE plpgsql
SET search_path = public  -- pinned so the function can't be hijacked by another schema (Supabase advisor)
AS $$
BEGIN
  -- Lock the group row so two concurrent joins can't both squeeze in as #10.
  PERFORM 1 FROM friend_groups WHERE id = NEW.group_id FOR UPDATE;
  IF (SELECT count(*) FROM group_memberships WHERE group_id = NEW.group_id) >= 10 THEN
    RAISE EXCEPTION 'GROUP_FULL'
      USING ERRCODE = 'AU001',
            DETAIL  = format('Friend group %s already has 10 members.', NEW.group_id);
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER group_member_cap
  BEFORE INSERT OR UPDATE OF group_id ON group_memberships
  FOR EACH ROW EXECUTE FUNCTION enforce_group_member_cap();

-- ---------------------------------------------------------------------------
-- Matching
-- ---------------------------------------------------------------------------
CREATE TABLE group_likes (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_group_id    bigint        NOT NULL REFERENCES friend_groups(id) ON DELETE CASCADE,
  to_group_id      bigint        NOT NULL REFERENCES friend_groups(id) ON DELETE CASCADE,
  liked_by_user_id bigint        NOT NULL REFERENCES users(id)         ON DELETE CASCADE,
  decision         like_decision NOT NULL,
  created_at       timestamptz   NOT NULL DEFAULT now(),
  UNIQUE (from_group_id, to_group_id),   -- one decision per direction, no duplicate likes
  CHECK (from_group_id <> to_group_id)
);
CREATE INDEX group_likes_to_idx ON group_likes (to_group_id);

CREATE TABLE group_matches (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_low_id   bigint      NOT NULL REFERENCES friend_groups(id) ON DELETE CASCADE,
  group_high_id  bigint      NOT NULL REFERENCES friend_groups(id) ON DELETE CASCADE,
  matched_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (group_low_id, group_high_id),
  CHECK (group_low_id < group_high_id)
);
CREATE INDEX group_matches_high_idx ON group_matches (group_high_id);

-- ---------------------------------------------------------------------------
-- Chat
-- ---------------------------------------------------------------------------
CREATE TABLE chats (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id    bigint       NOT NULL UNIQUE REFERENCES group_matches(id) ON DELETE CASCADE,
  name        varchar(130) NOT NULL,
  created_at  timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE chat_participants (
  chat_id       bigint      NOT NULL REFERENCES chats(id)         ON DELETE CASCADE,
  user_id       bigint      NOT NULL REFERENCES users(id)         ON DELETE CASCADE,
  group_id      bigint      NOT NULL REFERENCES friend_groups(id) ON DELETE CASCADE,
  joined_at     timestamptz NOT NULL DEFAULT now(),
  last_read_at  timestamptz NOT NULL DEFAULT now(),
  typing_at     timestamptz,            -- last time they typed here; "is typing" for 5s after
  archived_at   timestamptz,
  deleted_at    timestamptz,
  PRIMARY KEY (chat_id, user_id)
);
CREATE INDEX chat_participants_user_idx ON chat_participants (user_id);

-- Business rule: a group chat has at most 30 people.
CREATE FUNCTION enforce_chat_participant_cap() RETURNS trigger
LANGUAGE plpgsql
SET search_path = public  -- pinned so the function can't be hijacked by another schema (Supabase advisor)
AS $$
BEGIN
  PERFORM 1 FROM chats WHERE id = NEW.chat_id FOR UPDATE;
  IF (SELECT count(*) FROM chat_participants WHERE chat_id = NEW.chat_id) >= 30 THEN
    RAISE EXCEPTION 'CHAT_FULL'
      USING ERRCODE = 'AU002',
            DETAIL  = format('Chat %s already has 30 people.', NEW.chat_id);
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER chat_participant_cap
  BEFORE INSERT OR UPDATE OF chat_id ON chat_participants
  FOR EACH ROW EXECUTE FUNCTION enforce_chat_participant_cap();

CREATE TABLE messages (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chat_id         bigint      NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
  sender_user_id  bigint      REFERENCES users(id) ON DELETE SET NULL,
  body            text        NOT NULL CHECK (char_length(btrim(body)) BETWEEN 1 AND 2000),
  created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX messages_chat_time_idx ON messages (chat_id, created_at);

-- Conversation starters for a new match chat ("Need an opener?"). The AI step writes 3 per chat
-- right after the match is created, or none if the AI call fails (server/src/lib/suggestions.js).
-- The chat offers the unused ones until both groups have sent a message.
CREATE TABLE chat_suggestions (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chat_id     bigint       NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
  text        varchar(120) NOT NULL CHECK (btrim(text) <> ''),
  used_at     timestamptz,           -- when someone sent a message that started from this one
  created_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX chat_suggestions_chat_idx ON chat_suggestions (chat_id);

-- A matched pair of groups met up in person (KR4). One row per confirmed meetup;
-- a match can have several. Kept when the confirming user is deleted.
CREATE TABLE meetups (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id              bigint      NOT NULL REFERENCES group_matches(id) ON DELETE CASCADE,
  confirmed_by_user_id  bigint      REFERENCES users(id) ON DELETE SET NULL,
  created_at            timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX meetups_match_idx ON meetups (match_id);

-- ---------------------------------------------------------------------------
-- Derived data
-- ---------------------------------------------------------------------------
-- A group's shared interests = the union of its members' interests.
-- Never stored, so it updates the moment a member edits their interests.
-- member_count = how many members list that interest (used for ordering chips).
CREATE VIEW group_shared_interests WITH (security_invoker = true) AS
SELECT gm.group_id,
       i.id                       AS interest_id,
       i.name                     AS interest_name,
       count(DISTINCT gm.user_id) AS member_count
FROM group_memberships gm
JOIN user_interests ui ON ui.user_id = gm.user_id
JOIN interests      i  ON i.id = ui.interest_id
GROUP BY gm.group_id, i.id, i.name;

-- Objective key results, computed live from the tables (one row, percentages 0-100).
--   KR1 connect_pct:   registered groups that matched with at least one other group
--   KR2 four_plus_pct: registered groups with 4 or more members
--   KR3 message_pct:   connected groups with a match chat where BOTH groups sent a message
--   KR4 meetup_pct:    connected groups with at least one confirmed meetup
-- A message counts toward its sender's group via chat_participants.group_id.
CREATE VIEW okr_metrics WITH (security_invoker = true) AS
WITH match_sides AS (
  SELECT id AS match_id, group_low_id AS group_id FROM group_matches
  UNION ALL
  SELECT id, group_high_id FROM group_matches
),
sending_sides AS (
  SELECT DISTINCT c.match_id, cp.group_id
  FROM messages m
  JOIN chats c              ON c.id = m.chat_id
  JOIN chat_participants cp ON cp.chat_id = m.chat_id AND cp.user_id = m.sender_user_id
),
exchanged_matches AS (
  SELECT match_id FROM sending_sides GROUP BY match_id HAVING count(*) = 2
),
counts AS (
  SELECT
    (SELECT count(*) FROM friend_groups)                                   AS total_groups,
    (SELECT count(DISTINCT group_id) FROM match_sides)                     AS connected_groups,
    (SELECT count(*) FROM (SELECT group_id FROM group_memberships
                           GROUP BY group_id HAVING count(*) >= 4) g)      AS four_plus_groups,
    (SELECT count(DISTINCT ms.group_id) FROM match_sides ms
       JOIN exchanged_matches e USING (match_id))                         AS messaging_groups,
    (SELECT count(DISTINCT ms.group_id) FROM match_sides ms
       JOIN meetups mu USING (match_id))                                   AS meetup_groups
)
SELECT total_groups, connected_groups, four_plus_groups, messaging_groups, meetup_groups,
       round(100.0 * connected_groups / nullif(total_groups, 0), 1)     AS kr1_connect_pct,
       round(100.0 * four_plus_groups / nullif(total_groups, 0), 1)     AS kr2_four_plus_pct,
       round(100.0 * messaging_groups / nullif(connected_groups, 0), 1) AS kr3_message_pct,
       round(100.0 * meetup_groups    / nullif(connected_groups, 0), 1) AS kr4_meetup_pct
FROM counts;

