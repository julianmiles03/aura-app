-- 009: the admin portal's own sign-in. Adds admin_users (email + bcrypt password hash) and
-- admin_sessions (one row per signed-in browser; the httpOnly cookie holds the token, this table
-- only its SHA-256 hash). Every /api/admin route except login, logout and session needs one.
-- Adds to an existing aura database WITHOUT wiping it. db/schema.sql already includes it.
-- Safe to re-run. Apply with: npm run db:migrate (before deploying the API that uses it).
-- It creates no accounts; make one with: npm run db:admin-account

BEGIN;

-- Create the tables as whichever role owns aura's other tables (aura_app on Find Friends App), even
-- when this is run with the postgres login. A table owned by anyone else would be closed to the
-- API (RLS is on with no policies, and only the owner gets past that) and would make the next
-- db:reset fail, because only the owner can drop it. SET LOCAL lasts until COMMIT.
DO $$
DECLARE
  app_owner name := (SELECT tableowner FROM pg_tables WHERE schemaname = 'public' AND tablename = 'users');
BEGIN
  IF app_owner <> current_user THEN
    EXECUTE format('SET LOCAL ROLE %I', app_owner);
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS admin_users (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_email     varchar(254) NOT NULL UNIQUE
                   CHECK (user_email = lower(btrim(user_email)) AND user_email LIKE '_%@_%'),
  user_password  text         NOT NULL CHECK (user_password ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$'),
  created_at     timestamptz  NOT NULL DEFAULT now(),
  last_login_at  timestamptz
);

CREATE TABLE IF NOT EXISTS admin_sessions (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_user_id  bigint       NOT NULL REFERENCES admin_users(id) ON DELETE CASCADE,
  token_hash     char(64)     NOT NULL UNIQUE,
  created_at     timestamptz  NOT NULL DEFAULT now(),
  expires_at     timestamptz  NOT NULL
);
CREATE INDEX IF NOT EXISTS admin_sessions_admin_idx ON admin_sessions (admin_user_id);

-- Like every other table: RLS on with no policies keeps Supabase's auto-generated REST API closed.
-- That matters most here: these rows are password hashes and session hashes.
ALTER TABLE admin_users    ENABLE ROW LEVEL SECURITY;
ALTER TABLE admin_sessions ENABLE ROW LEVEL SECURITY;

COMMIT;
